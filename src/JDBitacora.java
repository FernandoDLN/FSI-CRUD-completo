    public void obtenerConexion(Conexion cnx) {
        this.cnx = cnx;

        cnx.seleccionar(infante.curps, cbinfante);
        cnx.seleccionar(responsables.curps, cbresponsable);
        cnx.seleccionar(educadores.curps, cbeducador);

    }

    public void obtenerbitacora(bitacora bit) {
        lbfolio.setText(bit.folio);
        lbfecha.setText(bit.tiempo);
        cbTipo.setSelectedItem(bit.tipo);
        txtBservaciones.setText(bit.observaciones);
        cbinfante.setSelectedItem(bit.infante_curp);
        cbresponsable.setSelectedItem(bit.responsables_curpr);
        cbeducador.setSelectedItem(bit.educadores_curp);
    }

