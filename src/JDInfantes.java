    public void obtenerInfante(infante kid) {
        SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
        txtCurp.setText(kid.curp);
        txtNombre.setText(kid.nombre);
        CBsexo.setSelectedItem(kid.sexo);
        jComboBox2.setSelectedItem(kid.estado);

        try {
            if (kid.fecha != null && !kid.fecha.isEmpty()) {
                jSpinner1.setValue(format.parse(kid.fecha));
            }
        } catch (java.text.ParseException e) {
            System.err.println("Error al transformar la fecha: " + e.getMessage());
        }
    }

